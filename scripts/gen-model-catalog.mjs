#!/usr/bin/env node
// Regenerates internal/core/config/model_catalog.go from https://models.dev/api.json.
//
// Filtering approach follows the langgraph-agent-server sibling project's
// scripts/gen_model_list.py (tool-call-capable chat models only, substring + deprecated-
// generation + future-release exclusions), adapted to this repo's own provider vocabulary
// (anthropic | openai | gemini — internal/modules/librarian/provider/adapter.go) instead of
// LangChain's provider prefixes. Deliberately does NOT carry over that script's per-model
// pricing/opinion exclusion list (EXCLUDED_MODEL_IDS) — that was project-specific taste, not
// a filtering rule.
//
// Usage:
//   node scripts/gen-model-catalog.mjs

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_FILE = join(REPO_ROOT, "internal", "core", "config", "model_catalog.go");
const API_URL = "https://models.dev/api.json";

// models.dev provider id -> this repo's provider vocabulary.
const PROVIDER_MAP = { anthropic: "anthropic", openai: "openai", google: "gemini" };
const PROVIDER_ORDER = ["anthropic", "openai", "gemini"];

// Non-chat / specialist model ids (tts, image gen, embeddings, etc.) — same substring family
// the reference script uses.
const EXCLUDED_SUBSTRINGS = [
  "codex",
  "embed",
  "tts",
  "image",
  "audio",
  "live",
  "speech",
  "deep-research",
  "native-audio",
  "customtools",
  "realtime",
  "computer-use",
  "robotics",
];

function isDeprecatedGeneration(provider, id) {
  if (provider === "anthropic") {
    return id.startsWith("claude-3-") && !id.startsWith("claude-3-5-") && !id.startsWith("claude-3-7-");
  }
  if (provider === "openai") {
    if (id.startsWith("gpt-4o") || id === "gpt-4" || id === "gpt-4-turbo") return true;
    if (id === "o1" || id === "o3-mini") return true;
    return false;
  }
  if (provider === "google") {
    return id.startsWith("gemini-1.");
  }
  return false;
}

function flatten(data) {
  const out = [];
  for (const [providerId, providerData] of Object.entries(data)) {
    if (!PROVIDER_MAP[providerId] || typeof providerData !== "object" || providerData === null) continue;
    const models = providerData.models ?? {};
    for (const [modelId, model] of Object.entries(models)) {
      out.push({ ...model, provider: providerId, id: modelId });
    }
  }
  return out;
}

function filterModels(entries, cutoffDate) {
  return entries.filter((e) => {
    if (!e.tool_call) return false;
    const id = String(e.id ?? "").toLowerCase();
    if (EXCLUDED_SUBSTRINGS.some((sub) => id.includes(sub))) return false;
    if (isDeprecatedGeneration(e.provider, e.id ?? "")) return false;
    const releaseDate = e.release_date ?? "";
    if (releaseDate && releaseDate > cutoffDate) return false;
    return true;
  });
}

function sortModels(entries) {
  const rank = (e) => PROVIDER_ORDER.indexOf(PROVIDER_MAP[e.provider]);
  return [...entries].sort((a, b) => {
    const r = rank(a) - rank(b);
    if (r !== 0) return r;
    const da = a.release_date || "1970-01-01";
    const db = b.release_date || "1970-01-01";
    return db.localeCompare(da); // descending within provider
  });
}

function goStringLiteral(s) {
  return JSON.stringify(s);
}

function renderGo(models) {
  const providers = [];
  for (const m of models) {
    const mapped = PROVIDER_MAP[m.provider];
    if (!providers.includes(mapped)) providers.push(mapped);
  }
  providers.sort((a, b) => PROVIDER_ORDER.indexOf(a) - PROVIDER_ORDER.indexOf(b));

  const entryLines = models
    .map((m) => {
      const mapped = PROVIDER_MAP[m.provider];
      return `\t{ID: ${goStringLiteral(m.id)}, Name: ${goStringLiteral(m.name ?? m.id)}, Provider: ${goStringLiteral(mapped)}},`;
    })
    .join("\n");

  const providerLines = providers.map((p) => `\t\t${goStringLiteral(p)},`).join("\n");

  return `// Code generated by scripts/gen-model-catalog.mjs from https://models.dev/api.json. DO NOT EDIT.
// Regenerate with: node scripts/gen-model-catalog.mjs
//
// There is deliberately NO CI drift gate for this file: the source is a remote third-party API,
// and a network-dependent CI check would be flaky (the whole gate suite must pass offline).
// Regeneration is a manual, occasional act — run the command above and commit the result.
package config

// CatalogModel is one selectable LLM model entry (SPA model-picker + config surfaces).
type CatalogModel struct {
	ID       string \`json:"id"\`       // provider-native model id, e.g. the exact string LLM_MODEL takes
	Name     string \`json:"name"\`     // human display name
	Provider string \`json:"provider"\` // anthropic | openai | gemini
}

// ModelCatalog lists tool-call-capable chat models from anthropic, openai, and gemini,
// sorted by provider then release date descending. See the generator's header for the
// exclusion rules (non-chat specialist models, deprecated generations, not-yet-released).
var ModelCatalog = []CatalogModel{
${entryLines}
}

// CatalogProviders returns the distinct providers present in ModelCatalog, in catalog order.
func CatalogProviders() []string {
	return []string{
${providerLines}
	}
}
`;
}

async function main() {
  const today = new Date().toISOString().slice(0, 10);
  const res = await fetch(API_URL);
  if (!res.ok) {
    throw new Error(`fetch ${API_URL}: HTTP ${res.status}`);
  }
  const data = await res.json();

  const flat = flatten(data);
  const filtered = filterModels(flat, today);
  const sorted = sortModels(filtered);

  const content = renderGo(sorted);
  writeFileSync(OUTPUT_FILE, content);

  const counts = PROVIDER_ORDER.map(
    (p) => `${p}: ${sorted.filter((m) => PROVIDER_MAP[m.provider] === p).length}`,
  ).join(", ");
  console.error(`Wrote ${sorted.length} models to ${OUTPUT_FILE} (${counts})`);
}

main().catch((err) => {
  console.error(String(err?.stack ?? err));
  process.exit(1);
});
